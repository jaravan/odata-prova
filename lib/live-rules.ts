// Live mock rules: the server watches config.json and the files it extends, and when the mock
// rules change, the generated sets no write has changed are generated again (see
// Store.regenerate), so a saved rule shows on the next refresh:
//
//   config.json: mock rules changed
//     PurchaseOrderSet: regenerated
//     PurchaseOrderItemSet: has your changes, kept (restart to regenerate it)
//
// A mistake is logged with how to fix it, and the rows stay as they are: a typo never stops a
// running server. Only without persistence: several servers sharing a database would each
// regenerate, and a saved state has its own catching up to do at the next start.
//
// The folders of the files are watched, not the files: an editor that saves by writing a new
// file and renaming it over the old one would end a watch on the file, and a config.json
// written after the start is seen too.

import fs from "node:fs";
import path from "node:path";
import { isDeepStrictEqual } from "node:util";
import type { Model } from "./model.ts";
import { loadConfig } from "./config.ts";
import {
  regenerationNotes,
  resolveMockRules,
  ruleValues,
  type MockRules,
} from "./mock-rules.ts";
import type { Store } from "./store.ts";
import type { Queue } from "./queue.ts";
import type { ODataService } from "./service.ts";

// How long after the last change to a file it's read: an editor's save can be several writes
const SETTLE = 100;

function liveRules({
  modelDir,
  model,
  store,
  queue,
  services,
  mockRows,
  rules,
  log,
}: {
  modelDir: string;
  model: Model;
  store: Store;
  queue: Queue;
  services: ODataService[];
  mockRows: number;
  // The rules the rows were generated by
  rules: MockRules;
  log: (message: string) => void;
}): { reload: () => Promise<void>; close: () => void } {
  const own = path.join(modelDir, "config.json");
  let current = rules;
  let files = [...new Set([own, ...loadConfig(modelDir).files])];
  const watchers = new Map<string, fs.FSWatcher>();
  let timer: NodeJS.Timeout | undefined;

  // A watch on the folder of each file, none on folders no file is in any more
  function watch(): void {
    const dirs = new Set(files.map((f) => path.dirname(f)));
    for (const [dir, watcher] of watchers)
      if (!dirs.has(dir)) {
        watcher.close();
        watchers.delete(dir);
      }
    for (const dir of dirs) {
      if (watchers.has(dir)) continue;
      try {
        const watcher = fs.watch(dir, (_, name) => {
          // Some platforms don't say which file changed
          if (name && !files.includes(path.join(dir, name.toString()))) return;
          clearTimeout(timer);
          timer = setTimeout(() => void reload(), SETTLE);
        });
        // A folder removed: nothing more to watch there
        watcher.on("error", () => watchers.delete(dir));
        watchers.set(dir, watcher);
      } catch {
        // A folder that isn't there (an extends to a missing file, an error of its own)
      }
    }
  }

  async function reload(): Promise<void> {
    let next: MockRules;
    try {
      const config = loadConfig(modelDir);
      files = [...new Set([own, ...config.files])];
      next = resolveMockRules(model, config.mock, mockRows);
    } catch (e) {
      log(
        `${(e as Error).message}\n  The rows are as they were: fix it and save again`,
      );
      return;
    } finally {
      watch();
    }
    if (isDeepStrictEqual(ruleValues(next), ruleValues(current))) return;
    const before = current;
    let result: ReturnType<Store["regenerate"]>;
    try {
      result = await queue.run(() => store.regenerate(next));
    } catch (e) {
      log(
        `${own}: the mock rules changed, but the rows couldn't be regenerated: ${(e as Error).message}`,
      );
      return;
    }
    current = next;
    for (const service of services)
      for (const set of result.regenerated) service.deltaTokens.forget(set);
    // Sets kept whose rules changed: there's a write in them, or rows kept point at them
    const ruled = (set: string) =>
      !isDeepStrictEqual(ruleValues(before)[set], ruleValues(next)[set]);
    const lines = regenerationNotes(
      store,
      result,
      ruled,
      "restart to regenerate it",
    );
    log(
      lines.length
        ? `${own}: mock rules changed\n${lines.join("\n")}`
        : `${own}: mock rules changed, no generated row changes`,
    );
  }

  watch();
  return {
    reload,
    close() {
      clearTimeout(timer);
      for (const watcher of watchers.values()) watcher.close();
      watchers.clear();
    },
  };
}

export { liveRules };
